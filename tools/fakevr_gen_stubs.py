"""Generates src/fakevr/stubs.gen.h: for every OpenVR interface class in openvr.h, a class
`Stub<Name>` deriving from it whose every method logs its first calls (fv_stub) and returns a
zero/empty default. The fake runtime (src/fakevr/) derives from these and overrides the methods it
models, so each vtable matches the header's interface version exactly (the compiler builds it).

    .venv\\Scripts\\python.exe -I tools\\fakevr_gen_stubs.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "third_party" / "openvr" / "headers" / "openvr.h"
OUT = ROOT / "src" / "fakevr" / "stubs.gen.h"

CLASSES = [
    "IVRSystem", "IVRApplications", "IVRSettings", "IVRChaperone", "IVRChaperoneSetup", "IVRCompositor",
    "IVRHeadsetView", "IVRNotifications", "IVROverlay", "IVROverlayView", "IVRRenderModels", "IVRExtendedDisplay",
    "IVRTrackedCamera", "IVRScreenshots", "IVRResources", "IVRDriverManager", "IVRInput", "IVRIOBuffer",
    "IVRSpatialAnchors", "IVRDebug",
]


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def class_body(text: str, name: str) -> str:
    m = re.search(r"\bclass\s+%s\b[^;{]*\{" % name, text)
    if not m:
        sys.exit(f"class {name} not found")
    i, depth = m.end(), 1
    while depth:
        c = text[i]
        depth += c == "{"
        depth -= c == "}"
        i += 1
    return text[m.end():i - 1]


def methods(body: str):
    for m in re.finditer(r"virtual\s+(.*?)\s*=\s*0\s*;", body, flags=re.S):
        decl = " ".join(m.group(1).split())
        decl = re.sub(r"VR_ARRAY_COUNT\s*\([^)]*\)\s*", "", decl)
        decl = re.sub(r"VR_OUT_STRING\s*\(\s*\)\s*", "", decl)
        decl = re.sub(r"VR_OUT_STRING_COUNT\s*\([^)]*\)\s*", "", decl)
        p = decl.index("(")
        head, params = decl[:p].strip(), decl[p:]
        name = re.search(r"(\w+)$", head).group(1)
        ret = head[: -len(name)].strip()
        # Drop default arguments (legal on overrides, but they would only add noise).
        inner = params[1:params.rindex(")")]
        args = [re.sub(r"\s*=\s*[^,]+$", "", a.strip()) for a in inner.split(",")] if inner.strip() else []
        tail = params[params.rindex(")") + 1:].strip()
        yield ret, name, ", ".join(args), tail


def main():
    text = strip_comments(HEADER.read_text(encoding="utf-8", errors="replace"))
    out = [
        "// Generated by tools/fakevr_gen_stubs.py from third_party/openvr/headers/openvr.h; do not edit.",
        "#pragma once",
        "#include <openvr.h>",
        "",
        "namespace fv {",
        "using namespace vr;",
        "void stub_called(const char* what);  // logs the first calls of each stub",
        "",
    ]
    total = 0
    for cls in CLASSES:
        out.append(f"class Stub{cls} : public vr::{cls} {{")
        out.append("public:")
        for ret, name, args, tail in methods(class_body(text, cls)):
            total += 1
            out.append("    " + f"{ret} {name}({args}) {tail} override {{".replace("  ", " "))
            out.append(f'        stub_called("{cls}::{name}");')
            if ret != "void":
                default = '""' if ret.replace(" ", "") == "constchar*" else "{}"
                out.append(f"        return {default};")
            out.append("    }")
        out.append("};")
        out.append("")
    out.append("}  // namespace fv")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(CLASSES)} classes, {total} methods")


if __name__ == "__main__":
    main()
